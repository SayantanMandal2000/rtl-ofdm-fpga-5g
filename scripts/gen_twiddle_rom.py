#!/usr/bin/env python3
"""Generate twiddle_rom.v : N/2-entry cos/sin ROM in signed Q1.14 (16-bit).

    W_N^k = cos(2*pi*k/N) - j*sin(2*pi*k/N)      (forward FFT)
    ROM stores c = cos(2*pi*k/N), s = sin(2*pi*k/N); the FFT core picks the sign.

Usage: python3 gen_twiddle_rom.py [N] > ../rtl/twiddle_rom.v
"""
import math
import sys

N = int(sys.argv[1]) if len(sys.argv) > 1 else 128
LOGN = int(math.log2(N))
assert 1 << LOGN == N, "N must be a power of two"
FRAC = 14
SCALE = 1 << FRAC

def q(v):
    x = int(round(v * SCALE))
    x = max(min(x, 32767), -32768)
    return x & 0xFFFF

out = []
out.append("// Auto-generated by scripts/gen_twiddle_rom.py  (N = %d)" % N)
out.append("// Twiddle ROM: c = cos(2*pi*k/N), s = sin(2*pi*k/N), signed Q1.14")
out.append("`timescale 1ns / 1ps")
out.append("module twiddle_rom #(")
out.append("    parameter LOGN = %d" % LOGN)
out.append(")(")
out.append("    input  wire [LOGN-2:0]    addr,")
out.append("    output reg  signed [15:0] cos_o,")
out.append("    output reg  signed [15:0] sin_o")
out.append(");")
out.append("    always @(*) begin")
out.append("        case (addr)")
for k in range(N // 2):
    a = 2 * math.pi * k / N
    out.append("            %d'd%-3d: begin cos_o = 16'h%04X; sin_o = 16'h%04X; end"
               % (LOGN - 1, k, q(math.cos(a)), q(math.sin(a))))
out.append("            default: begin cos_o = 16'h4000; sin_o = 16'h0000; end")
out.append("        endcase")
out.append("    end")
out.append("endmodule")
print("\n".join(out))
